def merge_group_column(ws, col, start_row, end_row, fill=None):
    """1열의 연속된 동일 그룹 값을 세로 병합하고 연파랑 채우기."""
    r = start_row
    while r <= end_row:
        val = ws.cell(row=r, column=col).value
        r2 = r
        while r2 + 1 <= end_row and ws.cell(row=r2 + 1, column=col).value == val:
            r2 += 1
        if r2 > r:
            ws.merge_cells(start_row=r, start_column=col, end_row=r2, end_column=col)
        c = ws.cell(row=r, column=col)
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        c.font = Font(name="맑은 고딕", bold=True, size=10, color="1F3864")
        if fill is not None:
            for rr in range(r, r2 + 1):
                ws.cell(row=rr, column=col).fill = fill
        r = r2 + 1


