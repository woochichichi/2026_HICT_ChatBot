# 공통 서식 상수
# ---------------------------------------------------------------------------
HEADER_FILL = PatternFill("solid", fgColor="1F3864")   # 진한 남색 헤더
HEADER_FONT = Font(name="맑은 고딕", bold=True, color="FFFFFF", size=11)
BODY_FONT   = Font(name="맑은 고딕", size=10)
TITLE_FONT  = Font(name="맑은 고딕", bold=True, size=16, color="1F3864")
SUB_FONT    = Font(name="맑은 고딕", bold=True, size=11, color="1F3864")

FILL_INCLUDE = PatternFill("solid", fgColor="E2EFDA")   # 포함=연녹
FILL_ADD     = PatternFill("solid", fgColor="FFF2CC")   # 추가후보=연노랑
FILL_DROP    = PatternFill("solid", fgColor="D9D9D9")   # 뺄후보=연회
FILL_GROUP   = PatternFill("solid", fgColor="DDEBF7")   # 그룹 구분(연파랑)

THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)

WRAP_TOP  = Alignment(wrap_text=True, vertical="top", horizontal="left")
WRAP_CTR  = Alignment(wrap_text=True, vertical="center", horizontal="center")


def style_header(ws, ncols, row=1):
    """헤더 행에 남색 배경+흰 글씨+굵게+테두리 적용 후 틀고정."""
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = BORDER
    ws.row_dimensions[row].height = 30
    ws.freeze_panes = ws.cell(row=row + 1, column=1)


def write_rows(ws, rows, start_row=2, fill=None, wrap_cols=None):
    """데이터 행을 쓰고 wrap/테두리/채우기 적용. wrap_cols=긴 텍스트 컬럼 인덱스(1-base) 집합."""
    wrap_cols = wrap_cols or set()
    for i, row in enumerate(rows):
        r = start_row + i
        for j, val in enumerate(row):
            cell = ws.cell(row=r, column=j + 1, value=val)
            cell.font = BODY_FONT
            cell.border = BORDER
            if (j + 1) in wrap_cols:
                cell.alignment = WRAP_TOP
            else:
                cell.alignment = Alignment(wrap_text=True, vertical="top", horizontal="left")
            if fill is not None:
                cell.fill = fill
    return start_row + len(rows)


def set_widths(ws, widths):
    """컬럼 너비 지정. widths=리스트(1-base 순서)."""
    for i, w in enumerate(widths):
        ws.column_dimensions[get_column_letter(i + 1)].width = w


